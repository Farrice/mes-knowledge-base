def family_for(name: str) -> str | None:
    for display, prefixes in FAMILIES:
        for pre in prefixes:
            if name == pre or name.startswith(pre + "-"):
                return display
    return None


_SKILL_REF_RE = re.compile(r"skills/([^/]+)/workflows/")


def skill_family_of(name: str) -> str | None:
    """The skill a command's wrapper executes into, if any.

    Menu wrappers embed the full `skills/<skill>/workflows/<file>.md` path, so
    the family is read off disk rather than guessed from the command's prefix.
    """
    p = WF_DIR / f"{name}.md"
    if not p.exists():
        return None
    m = _SKILL_REF_RE.search(p.read_text(encoding="utf-8", errors="replace"))
    if not m:
        return None
    skill = m.group(1)
    # Some workflow docs contain template EXAMPLES like `skills/[skill-name]/...`.
    # Only a directory that actually exists counts as a family.
    return skill if (ROOT / "skills" / skill).is_dir() else None


def build_appendix(missing: dict[str, str]) -> str:
    """Family-rollup index, not one row per command.

    WHY (2026-07-25, Arsenal Loop): this file is a DOCUMENT — the model reads it
    on demand per CLAUDE.md, and nothing fires from it (the native `/` menu is
    powered by .claude/commands/*.md, which stays complete). Emitting one
    described row per command took it to 592KB, well past the 350KB bloat
    threshold health_metrics.py flags, making a single read a context grenade.

    So: skill families collapse to one row each (count + front door + how to
    expand), and standalone commands list as bare names. Nothing becomes
    unreachable — `/arsenal` serves descriptions on demand at a few hundred
    tokens instead of hundreds of kilobytes.
    """
    by_skill: dict[str, list[str]] = {}
    standalone: list[str] = []
    for name in sorted(missing):
        skill = skill_family_of(name)
        if skill:
            by_skill.setdefault(skill, []).append(name)
        else:
            standalone.append(name)

    lines: list[str] = [BEGIN, ""]
    total = len(missing)
    lines.append(f"## 📚 Complete Command Index — Everything Else ({total})")
    lines.append("")
    lines.append(
        "Every command on disk that isn't already described in a curated section above. "
        "Auto-generated by `execution/generate_slash_commands.py`.\n\n"
        "**All of these fire right now** — the `/` typeahead in Claude Code reads "
        "`.claude/commands/`, which is complete. This page is a map, not the menu. "
        "Expert-skill commands are rolled up by family so the file stays cheap to read; "
        "for descriptions, run **`/arsenal <what you're trying to do>`** or "
        "`python3 execution/arsenal.py --family <skill>`."
    )
    lines.append("")

    if by_skill:
        lines.append(f"### 🎓 Expert Skill Families ({sum(len(v) for v in by_skill.values())} "
                     f"commands across {len(by_skill)} families)")
        lines.append("")
        lines.append("| Family | Commands | Examples | See all |")
        lines.append("|--------|----------|----------|---------|")
        for skill in sorted(by_skill):
            cmds = by_skill[skill]
            front = f"`/{skill}`" if (CMD_DIR / f"{skill}.md").exists() else "—"
            examples = ", ".join(f"`/{c}`" for c in cmds[:3])
            if len(cmds) > 3:
                examples += ", …"
            lines.append(f"| {front} **{skill}** | {len(cmds)} | {examples} "
                         f"| `/arsenal --family {skill}` |")
        lines.append("")

    if standalone:
        lines.append(f"### 🗂️ Standalone Workflows — A–Z ({len(standalone)})")
        lines.append("")
        lines.append("Names only — run `/arsenal <task>` for what each one does.")
        lines.append("")
        current = ""
        bucket: list[str] = []
        for c in standalone:
            letter = c[0].upper()
            if letter != current:
                if bucket:
                    lines.append(f"**{current}** · " + " · ".join(f"`/{x}`" for x in bucket))
                    lines.append("")
                current, bucket = letter, []
            bucket.append(c)
        if bucket:
            lines.append(f"**{current}** · " + " · ".join(f"`/{x}`" for x in bucket))
            lines.append("")

    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    check = "--check" in sys.argv
    md_text = MD.read_text(encoding="utf-8")

    # lift the quick-tip footer from anywhere in the doc so it re-emits last
    footer_re = re.compile(r'^> \*\*Quick tip:\*\*.*$', re.MULTILINE)
    fm = footer_re.search(md_text)
    footer = fm.group(0) if fm else ""
    # strip any prior auto region, then rebuild head
    if BEGIN in md_text:
        head = md_text.split(BEGIN)[0]
    else:
        head = md_text
    if footer:
        head = footer_re.sub("", head)
    # drop trailing "---" separators left behind by removed blocks
    head = re.sub(r'(\n---\s*)+$', '', head).rstrip()

    universe = all_command_names()
    documented = documented_in_md(head)
    missing_names = sorted(universe - documented)
    missing = {n: best_description(n) for n in missing_names}

    print(f"total commands on disk : {len(universe)}")
    print(f"already documented     : {len(documented)}")
    print(f"missing (to append)    : {len(missing)}")
    stale = sorted(documented - universe)
    if stale:
        print(f"documented but no file : {len(stale)} -> {', '.join(stale[:10])}"
              + (" ..." if len(stale) > 10 else ""))

    if check:
        return 0

    appendix = build_appendix(missing)
    new_text = head + "\n\n---\n\n" + appendix + "\n"
    if footer:
        new_text += "\n---\n\n" + footer.strip() + "\n"

    # refresh the headline count on line 1
    grand_total = len(documented | universe)
    new_text = re.sub(
        r'# 🚀 Antigravity Workflows — Complete Index \(\d+ Commands\)',
        f'# 🚀 Antigravity Workflows — Complete Index ({grand_total} Commands)',
        new_text, count=1,
    )

    MD.write_text(new_text, encoding="utf-8")
    print(f"wrote {MD} ({grand_total} commands total)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
