#!/usr/bin/env python3
"""
generate_slash_commands.py — keep SLASH_COMMANDS.md complete and current.

Strategy (non-destructive):
  1. Preserve the entire hand-curated SLASH_COMMANDS.md verbatim (all curated
     descriptions, the Natural-Language-Triggers table, How-I-Write OS, Fork
     Harvest — none of it is touched).
  2. Scan every real command source (.agent/workflows/*.md + .claude/commands/*.md),
     union by command name, pull the best available one-line description.
  3. Append a single auto-generated region ("Complete Command Index — Everything
     Else") holding every command NOT already documented above, grouped by
     expert-family / theme, in the same `| Command | What It Does |` format.
  4. Idempotent: the appended region is fenced by sentinel comments and rebuilt
     on every run, so re-running never duplicates.

Run:  python3 execution/generate_slash_commands.py
      python3 execution/generate_slash_commands.py --check   # report only, no write
"""
from __future__ import annotations
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MD = ROOT / "SLASH_COMMANDS.md"
WF_DIR = ROOT / ".agent" / "workflows"
CMD_DIR = ROOT / ".claude" / "commands"

BEGIN = "<!-- AUTO-INDEX:BEGIN (generated by execution/generate_slash_commands.py — do not edit by hand) -->"
END = "<!-- AUTO-INDEX:END -->"

# ── description extraction ────────────────────────────────────────────────
FRONTMATTER_DESC = re.compile(r'^description:\s*(.+?)\s*$', re.MULTILINE)


def clean(text: str) -> str:
    text = text.strip().strip('"').strip("'").strip()
    text = re.sub(r'\s+', ' ', text)
    return text


def yaml_desc(fm: str) -> str:
    """Pull `description:` from a YAML frontmatter block, handling both inline
    values and `|`/`>` block scalars (text on following indented lines)."""
    lines = fm.splitlines()
    for i, line in enumerate(lines):
        m = re.match(r'^description:\s*(.*)$', line)
        if not m:
            continue
        val = m.group(1).strip().strip('"').strip("'").strip()
        if re.fullmatch(r'[|>][-+]?', val) or val == "":
            # block scalar — gather following indented lines
            block = []
            for nxt in lines[i + 1:]:
                if nxt.strip() == "":
                    if block:
                        break
                    continue
                if nxt.startswith((" ", "\t")):
                    block.append(nxt.strip())
                else:
                    break
            return clean(" ".join(block))
        return clean(val)
    return ""


def _slug(s: str) -> str:
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')


def extract_description(path: Path, name: str = "", _depth: int = 0) -> str:
    try:
        raw = path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return ""
    # 1. frontmatter description: — fenced (---) or unfenced YAML at file head
    fm = None
    if raw.startswith("---"):
        end = raw.find("\n---", 3)
        if end != -1:
            fm = raw[3:end]
    if fm is None:
        # unfenced: treat the leading run of "key: value" lines as frontmatter
        head_lines = []
        for line in raw.splitlines():
            if re.match(r'^[a-zA-Z_][\w-]*:\s', line) or (head_lines and line.startswith((' ', '"', '-', '['))):
                head_lines.append(line)
            else:
                break
        fm = "\n".join(head_lines)
    if fm:
        d = yaml_desc(fm)
        if d:
            return d
    # 2. command-wrapper pattern: "... — <desc>"
    m = re.search(r'Read and execute the workflow at `[^`]+`\s*[—-]\s*(.+)', raw)
    if m:
        return clean(m.group(1)).strip('"')
    # 2b. skill-command shim: resolve to the target SKILL.md description
    m = re.search(r'Load and embody the skill at `(skills/[^`]+/SKILL\.md)`', raw)
    if m:
        skill = ROOT / m.group(1)
        if skill.exists():
            sraw = skill.read_text(encoding="utf-8", errors="replace")
            sfm = sraw[3:sraw.find("\n---", 3)] if sraw.startswith("---") else sraw
            d = yaml_desc(sfm)
            if d:
                return d
    # 2c. "Run the **Bold Title** workflow" convention (prefer local title)
    m = re.search(r'Run the \*\*(.+?)\*\*', raw)
    if m:
        d = clean(m.group(1))
        if len(d) >= 6 and _slug(d) != name:
            return d
    # strip frontmatter from the body before prose/heading scanning
    body = raw
    if raw.startswith("---"):
        e = raw.find("\n---", 3)
        if e != -1:
            body = raw[e + 4:]

    # 3. first substantive prose line (incl. blockquote) under the title
    for line in body.splitlines():
        s = line.strip()
        if not s or s.startswith(("#", "|", "```", "---", "<!--")):
            continue
        s = re.sub(r'^>\s*', '', s)              # unwrap blockquote
        if re.match(r'^[a-zA-Z_][\w-]*:\s', s):  # skip stray yaml
            continue
        if re.match(r'^[-*]?\s*\*\*[^*]+\*\*\s*:', s):  # skip bold metadata labels
            continue
        if re.match(r'^(\d+[.)]|[-*+])\s', s):          # skip list items
            continue
        if len(s) >= 20 and " " in s and _slug(s) != name:
            return clean(s)

    # 4. fallback: first heading that isn't the name or a generic section label
    GENERIC = {"trigger", "workflow", "usage", "quick use", "quick start",
               "instructions", "produces", "output", "overview", "steps",
               "context required", "when to use", "inputs", "process",
               "requirements", "notes", "example", "examples", "goal"}
    for line in body.splitlines():
        line = line.strip()
        if line.startswith("#"):
            h = clean(line.lstrip("#").strip())
            h = re.sub(r'^[/`]+|[`]+$', '', h)
            if (h and not h.startswith("PHASE")
                    and not re.match(r'^[a-zA-Z_][\w-]*:\s', h)
                    and _slug(h) != name
                    and h.lower() not in GENERIC):
                return h

    # 5. last resort: resolve a "skills/.../workflows/X.md" pointer if present
    if _depth < 2:
        m = re.search(r'`(skills/[^`]+/workflows/[^`]+\.md)`', raw)
        if m:
            tgt = ROOT / m.group(1)
            if tgt.exists() and tgt != path:
                d = extract_description(tgt, name, _depth + 1)
                if d and _slug(d) != name:
                    return d
    return ""


def best_description(name: str) -> str:
    # prefer the workflow definition, fall back to the command wrapper
    for base in (WF_DIR, CMD_DIR):
        p = base / f"{name}.md"
        if p.exists():
            d = extract_description(p, name)
            if d and _slug(d) != name:
                # truncate absurdly long descriptions to one readable line
                if len(d) > 240:
                    d = d[:237].rstrip() + "..."
                return d
    return "(workflow — see file for details)"


# ── collect universe + already-documented ────────────────────────────────
def all_command_names() -> set[str]:
    names = set()
    for base in (WF_DIR, CMD_DIR):
        if base.exists():
            for p in base.glob("*.md"):
                names.add(p.stem)
    return names


def documented_in_md(md_text: str) -> set[str]:
    # strip the auto region before scanning so its own entries don't count
    if BEGIN in md_text:
        md_text = md_text.split(BEGIN)[0]
    return set(re.findall(r'`/([a-z0-9][a-z0-9-]*)`', md_text))


